#!/usr/bin/env python3
"""floorfloor1 (bridge #13): the user's floor<->floor loop on Minecraft blocks, where Chell ended behind a floor
portal's plane with no transit (bridge.log ~230900, transits 25/26: in 44.6 u off the entry portal's centre at 750 u/s,
out of the other floor portal 44 u off centre and 26 u behind its plane, the hull against the block rim; she stopped
rising and sank). Two floor portals shot with the gun on a stone slab in open air (floorloop2's setup: yaws differ, as
in the user's pair); Chell is put above portal 1 at an offset along its long / short axis and sent into it at a speed
and entry angle, then left to loop for 2 s. Asserts per case: at least 2 transits, never more than 48 u behind a
portal's plane, never stuck in a block. pcb_exit_recentre 0 gives the old behaviour (control).
World hygiene: the slab changes region r.-1.0.mca (back it up and restore it after Minecraft has quit)."""
import sys

out = []
w = out.append
w("# generated by tools/gen_floorfloor.py: " + __doc__.splitlines()[0])
for line in __doc__.splitlines()[1:]:
    w("# " + line if line else "#")
w("""pcb_assert_soft 1
sv_cheats 1
pcb_audio_test_mute 1
waituntil spawned 600
waituntil link 9000
waituntil haveexit 3600
pc_pit_redirect 0
pcb_chell_proxy 0
pcb_mc_cmd time set noon
pcb_noclip_set 1
pcb_mc_cmd fill -362 85 478 -348 99 494 stone
pcb_mc_cmd fill -362 100 478 -348 106 494 air
pcb_light_goto_mc -355 106 486 90 0
pcb_stop
wait 60
waituntil near 1800
waituntil terrain_idle 1200
pcb_light_goto_mc -351.5 104 482.5 0 89
pcb_stop
wait 20
+attack
wait 6
-attack
wait 40
pcb_light_goto_mc -357.5 104 489.5 -115 89
pcb_stop
wait 20
+attack2
wait 6
-attack2
wait 60
pcb_assert_portals
pcb_exit_recentre""")
speeds = [300, 750, 1000]
offsets = [(0, 0), (30, 0), (44, 0), (50, 0), (0, 20), (0, 26), (36, 18)]
angles = [0, 30]  # entry angle from straight down (deg), tilted along world +x
import math
for sp in speeds:
    for (ou, orr) in offsets:
        for ang in angles:
            if ang and (ou, orr) not in [(0, 0), (44, 0), (0, 26)]:
                continue
            vx = sp * math.sin(math.radians(ang))
            vz = -sp * math.cos(math.radians(ang))
            w(f"pcb_log CASE speed {sp} angle {ang} offset long {ou} short {orr}")
            w("pcb_noclip_set 1")
            w(f"pcb_goto_portal 1 60 {ou} {orr}")
            w("pcb_stop\nwait 20")
            w("pcb_assert_behind_portal reset\npcb_assert_stuck reset\npcb_assert_transits reset")
            w("pcb_noclip_set 0")
            w(f"pcb_launch_vel {vx:.0f} 0 {vz:.0f}")
            w("pcb_track 150 6\nwait 120\npcb_where")
            w("pcb_assert_transits 2\npcb_assert_behind_portal 48\npcb_assert_stuck")
w("pcb_noclip_set 1\npcb_exit_recentre\npcb_unstick\npcb_mc_cmd fill -362 85 478 -348 106 494 air")
w("pcb_assert_mc_alive 30\npcb_run_summary\nquit")
open(sys.argv[1] if len(sys.argv) > 1 else "tools/cfg/floorfloor1.txt", "w").write("\n".join(out) + "\n")
