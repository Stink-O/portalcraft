#!/usr/bin/env python3
"""Bridge #29: generate the pc_testbed test cfgs from the map's layout JSON (written by maps/tools/gen_testbed.py).

    tools/gen_tb_smoke.py [layout.json]            # writes tools/cfg/tb_smoke.txt and tb_startmc.txt
    tools/gen_tb_smoke.py --only lift,laser        # a subset of bays (for debugging one mechanic)

    PCB_SO=<abs .so> tools/locked_run.sh mirror tools/cfg/tb_smoke.txt pc_testbed 1800 tb_smoke
    PCB_PRE="pc_start_mode mc" PCB_SO=<abs .so> tools/locked_run.sh mirror tools/cfg/tb_startmc.txt pc_testbed 400 tb_startmc
    tools/tb_check.py cache/bridge/shots/tb_smoke/bridge.log

The cfgs name entities only (tb_spot_<bay>, the bay's main entity, tb_go_<bay> / tb_reset_<bay>); positions come from the
map at run time through pcb_goto / pcb_face / pcb_stand_on. A layout change in gen_testbed.py regenerates the tests.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT = os.path.join(HERE, "cfg", "pc_testbed_layout.json")
FPS = 200   # wait units are frames (~170-180 fps in the runs); the map moves in seconds, so overshoot rather than undershoot


def frames(s):
    return int(s * FPS)


def bay_lines(d, name, mc):
    b = d["bays"][name]
    main = b["main"]
    spot = b["spot"]["name"]
    go, rs = b["relays"]["go"]["name"], b["relays"]["reset"]["name"]
    who = "mc" if mc else "chell"
    out = ["pcb_log TB %s %s: %s" % (name, who, b["relays"]["go"]["expect"][:110])]
    out += ["pcb_goto %s 64" % spot]
    if mc:
        out += ["waituntil mcleads 1200", "wait 40"]
    else:
        out += ["wait 40"]
    out += ["pcb_face %s" % main, "wait 4", "pcb_glhud_shot tb_%s_%s_0" % (name, who)]
    if mc and b["ride"]:
        out += ["pcb_assert_mc_rode reset", "pcb_stand_on %s" % ("@%g,%g,%g" % tuple(b["ride_at"]) if b.get("ride_at") else main), "wait 30", "waituntil mcleads 600",
                "pcb_assert_mc_platform 1", "pcb_where"]
    spin = mc and b["ride"] and name == "rotate"   # (bridge #31) a turntable: the rider goes round with it, the view turns with it
    if spin:
        out += ["pcb_ride_spin reset"]
    out += ["ent_fire %s trigger" % go]
    out += ["wait %d" % frames(b["settle_s"])]
    if mc and b["ride"] and b.get("ride_moves"):
        out += ["pcb_assert_mc_rode 8 0", "pcb_where"]
        if spin:
            out += ["pcb_ride_spin assert 30 10"]
    else:
        out += ["pcb_face %s" % main, "wait 4"]
    out += ["pcb_glhud_shot tb_%s_%s_1" % (name, who), "ent_fire %s trigger" % rs, "wait %d" % frames(b["settle_s"])]
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--only" in sys.argv:
        pass
    only = None
    if "--only" in sys.argv:
        only = sys.argv[sys.argv.index("--only") + 1].split(",")
        args = [a for a in args if a != sys.argv[sys.argv.index("--only") + 1]]
    path = args[0] if args else LAYOUT
    d = json.load(open(path))
    order = [n for n in d["order"] if not only or n in only]
    hdr = ["# tb_smoke (generated by tools/gen_tb_smoke.py from %s; do not edit by hand)" % os.path.basename(path),
           "# Phase 1: Chell visits each bay (pcb_goto its tb_spot_<bay>, pcb_face its main entity), shoots, fires tb_go_<bay>, shoots, fires tb_reset_<bay>.",
           "# Phase 2: the same as the Minecraft player (bridge_mode mc); movers it can ride are stood on and checked.",
           "sv_cheats 1", "pcb_assert_soft 1", "waituntil spawned 600", "waituntil link 9000", "wait 240", "pcb_mapindex write",
           "pcb_log TB index: %d bays" % len(order)]
    # every entity of the layout that is a real BSP entity must be in the index (tb_check.py compares; pcb_find prints the entry)
    ents = []
    for n in order:
        for en, e in d["bays"][n]["entities"].items():
            if e.get("classname") != "func_instance":
                ents.append(en)
        ents += [d["bays"][n]["relays"]["go"]["name"], d["bays"][n]["relays"]["reset"]["name"], d["bays"][n]["spot"]["name"]]
    lines = list(hdr) + ["pcb_log TB find %s" % e for e in ents[:0]] + ["pcb_find tb_", "pcb_movers write"]
    lines.append("noclip")
    for n in order:
        lines += bay_lines(d, n, False)
    if "--probe" in sys.argv:
        p = hdr[3:7] + ["wait 200", "noclip"]
        p += ["pcb_probe 0 0 64", "pcb_probe 700 700 64", "pcb_probe -700 -700 200"]
        for n in order:
            b = d["bays"][n]
            ins = b["inside"]["origin"]
            p += ["pcb_goto %s 64" % b["spot"]["name"], "wait 150", "pcb_face %s" % b["main"], "wait 30", "pcb_glhud_shot tb_probe_%s" % n,
                  "pcb_probe %.0f %.0f %.0f" % (ins[0], ins[1], 56)]
        p += ["pcb_run_summary", "quit"]
        open(os.path.join(HERE, "cfg", "tb_probe.txt"), "w").write("\n".join(p) + "\n")
        print("wrote tb_probe.txt")
        return
    if "--chell" in sys.argv:
        lines += ["pcb_run_summary", "quit"]
        open(os.path.join(HERE, "cfg", "tb_look.txt"), "w").write("\n".join(lines) + "\n")
        print("wrote tb_look.txt (Chell phase only)")
        return
    lines += ["pcb_log TB phase 2: Minecraft player", "bridge_mode mc", "waituntil mcmode 2400", "waituntil mcleads 2400", "wait 120", "pcb_assert_mc_feet_above reset"]
    for n in order:
        lines += bay_lines(d, n, True)
    lines += ["pcb_movers write", "pcb_log TB done", "pcb_run_summary", "quit"]
    out = os.path.join(HERE, "cfg", "tb_smoke.txt" if not only else "tb_smoke_part.txt")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote", out, len(lines), "lines")
    # start-as-Minecraft flow (PCB_PRE="pc_start_mode mc"): the map starts in the hall, the arrival logic is fired by hand
    s = ["# tb_startmc (generated): pc_start_mode mc (PCB_PRE), start in the testbed hall as the Minecraft player, then ride the arrival car",
         "sv_cheats 1", "pcb_assert_soft 1", "pcb_assert_mc_feet_above reset", "waituntil spawned 600", "waituntil link 9000", "waituntil mcmode 2400", "pcb_assert_mc_mode 1", "pcb_where",
         "pcb_glhud_shot tb_startmc_0"]
    for nm in ("arrival",):   # the departure car is an invisible blocker pcb_stand_on skips
        if nm in d["bays"]:
            b = d["bays"][nm]
            s += ["pcb_log TB startmc %s" % nm, "pcb_goto %s 64" % b["spot"]["name"], "waituntil mcleads 1200", "wait 40", "pcb_face %s" % b["main"], "pcb_glhud_shot tb_startmc_%s_0" % nm,
                  "pcb_assert_mc_rode reset", "pcb_stand_on %s" % b["main"], "wait 30", "waituntil mcleads 600", "pcb_assert_mc_platform 1",
                  "ent_fire %s trigger" % b["relays"]["go"]["name"], "wait %d" % frames(b["settle_s"] + 4), "pcb_where", "pcb_glhud_shot tb_startmc_%s_1" % nm, "pc_mc_fall_guard"]
    s += ["pcb_run_summary", "quit"]
    open(os.path.join(HERE, "cfg", "tb_startmc.txt"), "w").write("\n".join(s) + "\n")
    # (bridge #31) the user's play_clip --start mc: the level STARTS inside the arrival car at the bottom of its shaft, as the Minecraft player.
    # Run it in the terrain world with a fresh Minecraft (locked_run.sh terrain), like play_clip: the car rises while the hand-over waits, and
    # Minecraft must come out of it riding the car, never on the shaft's floor (the player fell out: the hold released on that floor).
    st = d["start"]["origin"]
    bottom = st[2] - 120.0  # (the car's floor is ~64 u under the start; the shaft's floor is 190 u below it: 120 u under the start is already out of the car)
    s = ["# tb_startmc_play (generated, bridge #31): play_clip.sh --map pc_testbed --start mc, i.e.",
         "#   PCB_PRE=\"pc_start_mode mc\" PCB_SO=<abs .so> tools/locked_run.sh terrain tools/cfg/tb_startmc_play.txt pc_testbed 400 <run>",
         "sv_cheats 1", "pcb_assert_soft 1", "pcb_assert_mc_feet_above reset", "pcb_assert_mc_rode reset", "pcb_ride_track reset",
         "waituntil spawned 600", "waituntil link 9000", "waituntil mcmode 2400", "pcb_assert_mc_mode 1", "pcb_where", "pcb_glhud_shot tb_play_0",
         "pcb_setview 50 90", "wait 2", "pcb_glhud_shot tb_play_down", "pcb_setview 0 90",
         "waituntil mcleads 3600", "wait 600", "pcb_where", "pc_mc_fall_guard",
         "pcb_assert_mc_feet_above %.0f 0" % bottom, "pcb_assert_mc_rode 10 0", "pcb_assert_mc_mode 1", "pcb_assert_body_clear", "pcb_assert_mc_flag ground 1",
         "pcb_glhud_shot tb_play_end", "pcb_movers write", "pcb_run_summary", "quit"]
    open(os.path.join(HERE, "cfg", "tb_startmc_play.txt"), "w").write("\n".join(s) + "\n")


if __name__ == "__main__":
    main()
