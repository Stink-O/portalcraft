#!/usr/bin/env python3
"""Generate tools/cfg/mcworld1.txt: the standing regression suite for portals shot inside the
Minecraft world with Chell's real gun (bridge agent #6).

  tools/gen_mcworld.py [--short] [out=tools/cfg/mcworld1.txt]

Parts (each case logs "CASE <id>" and ends in pcb_assert_* lines; the run summary counts them):
  1. placement matrix: both colours on flat ground, the cliff face, a ceiling, a slope (valid by
     Portal 2's rules either way), next to a block edge (must bump), water / leaves / glass (rejected),
     re-firing the same colour (replace), a shot next to a weighted cube (prop collider pool)
  2. preview stability per pair and portal: 2 / 6 / 15 / 40 blocks, still / walk / strafe / 180 deg/s
     turn, every frame watched (mcworld mode) and the opening's twitch against the terrain measured
  3. pair geometries: ground<->cliff, cliff<->cliff side by side, ground<->ground (the endless fall),
     a facing pair (tunnel), Minecraft<->chamber; walk / jump / fling in, transits counted, never stuck
     in a block (block collision on)
  4. persistence: 30 s, night, the hidden player relocated (150 blocks out and back), chunks unloaded
     (~500 blocks out and back); the pair stays where it was and still carries Chell
  5. frame times (pcb_composite_lag windows without the per-frame readback)
"""
import sys

SHORT = "--short" in sys.argv
args = [a for a in sys.argv[1:] if not a.startswith("--")]
OUT = args[0] if args else "tools/cfg/mcworld1.txt"

GROUND = (-1911, -194, -15100)   # feet, hovering over flat ground below the cliff (MC ~ -375 64 428)
CLIFF = (-500, -40, -13950)      # feet, in front of the cliff face (MC x ~ -333)
CHAMBER_EYE = (300, -330, -768)  # feet on the pit floor, facing the portalable pit wall at y -512

L = []
def w(*lines):
    L.extend(lines)

def case(cid, text):
    w(f"pcb_log CASE {cid}: {text}")

def go(p, settle=60):
    w("pcb_noclip_set 1", f"setpos {p[0]} {p[1]} {p[2]}", "pcb_stop", "wait 30", "waituntil near 1800", f"wait {settle}")

def shoot(colour):
    b = "+attack" if colour == 0 else "+attack2"
    w("wait 20", b, "wait 6", "-" + b[1:], "wait 40")

def shot(cid, colour, kind, expect, orient="any", radius=24, like=-1, opt="", bump=0, where=None, shotname=None):
    case(cid, f"colour {colour} at {kind} ({expect})")
    if where:
        go(where)
    w("waituntil terrain_idle 1200", f"pcb_find_surface {kind} {radius} {like} {opt}".rstrip())
    if opt.startswith("place="):
        w("waituntil placed 600", "wait 30")
    shoot(colour)
    w(f"pcb_assert_gun_shot {colour} {expect} {orient} {bump}")
    if expect == "placed":
        w(f"pcb_assert_portal_face {colour}")  # (every test portal lies flush on a real block face)
    w("wait 20", f"screenshot pcb_{shotname or cid}")

w("# mcworld1: portals shot inside the Minecraft world with Chell's gun (generated by tools/gen_mcworld.py)",
  "pcb_assert_soft 1", "sv_cheats 1",
  "waituntil spawned 600", "waituntil link 9000", "waituntil haveexit 3600",
  "pc_pit_redirect 0", "pcb_noclip_set 1", "sv_noclipspeed 1", "cl_yawspeed 180",
  "pcb_chell_proxy 0", "pcb_assert_mc_alive reset", "pcb_composite_lag")

# ---- part 1: placement matrix ------------------------------------------------------------------
w("pcb_log PART1 placement matrix (real gun)")
go(GROUND, 120)
shot("P1", 0, "ground", "placed", "floor")
shot("P2", 1, "ground", "placed", "floor")
w("pcb_assert_portals")
shot("P3", 0, "slope", "valid", radius=32)
shot("P4", 1, "slope", "valid", radius=32)
shot("P5", 0, "edge", "placed", "floor", radius=48, bump=10, where=CLIFF)
shot("P6", 1, "edge", "placed", "floor", radius=48, bump=10)
go(GROUND)
shot("P7", 0, "water", "rejected", radius=40)
shot("P8", 1, "water", "rejected", radius=40)
go(GROUND)
shot("P9", 0, "ground", "rejected", radius=32, opt="place=oak_leaves[persistent=true]", shotname="P9_leaves")
w("pcb_place_clear", "wait 30")
shot("P10", 1, "ground", "rejected", radius=32, opt="place=glass", shotname="P10_glass")
w("pcb_place_clear", "wait 30")
shot("P11", 0, "ground", "placed", "floor", shotname="P11_replace")  # re-fire blue: it moves
shot("P12", 1, "ground", "placed", "floor", radius=32, opt="cube", shotname="P12_cube")
w("wait 60", "ent_fire pcb_mwcube kill", "wait 10")  # (Portal 2-lit: a white cube at night, until Minecraft lighting lands)
go(CLIFF, 120)
shot("P13", 0, "cliff", "placed", "wall")
shot("P14", 1, "cliff", "placed", "wall")
w("pcb_assert_portals")
shot("P15", 0, "ceiling", "placed", "ceiling", radius=64)
shot("P16", 1, "ceiling", "placed", "ceiling", radius=64)

# ---- parts 2, 3, 5 per pair --------------------------------------------------------------------
DISTS = [2, 6] if SHORT else [2, 6, 15, 40]

OPEN_AIR = set()  # pairs whose portals float in open air (pcb_portal): no terrain at the centre to measure twitch against

def view_suite(pair, i, kind):
    dists = [2, 3] if kind == "chamber" else DISTS
    for d in dists:
        lab = f"{pair}_p{i}_d{d}"
        w(f"pcb_log VIEW {lab}", f"pcb_view_from {i} {d}", "wait 40",
          "pcb_twitch reset", f"pcb_frame_watch 6000 {lab} mcworld", "pcb_assert_image_age reset",
          "wait 90", f"pcb_twitch report {lab}_still" + ("" if kind == "chamber" or pair in OPEN_AIR else " 0.5 2"), "pcb_assert_image_age 3 6",
          f"pcb_aim_track {i}", "+back", "wait 45", "-back", "+forward", "wait 45", "-forward", "pcb_aim_track off",
          f"pcb_twitch report {lab}_walk",
          f"pcb_aim_track {i}", "+moveleft", "wait 45", "-moveleft", "+moveright", "wait 45", "-moveright", "pcb_aim_track off",
          f"pcb_twitch report {lab}_strafe",
          "pcb_cam_turn 120 180", "wait 85", "pcb_cam_turn -120 180", "wait 85",
          f"pcb_twitch report {lab}_turn",
          "pcb_frame_watch 0", "wait 5", "pcb_assert_watch", "pcb_stop")
    w(f"pcb_view_from {i} 6", "wait 40", f"screenshot pcb_{pair}_view{i}")

def attempt(label, lines, want=1):
    w(f"pcb_log TRANSIT {label}")
    w(*lines[:-1], "pcb_track 240 6", lines[-1])
    w(f"pcb_assert_transits {want}", "pcb_aim_track off", "-forward", "-jump", "pcb_noclip_set 1", "pcb_stop", "wait 20")

def transits(pair, i, kind, reps=2):
    for r in range(reps):
        if kind in ("wall", "chamber"):
            near, mid, far = (100, 120, 220) if kind == "chamber" else (140, 160, 320)
            attempt(f"{pair} walk into {i} #{r}", ["pcb_noclip_set 0", "pcb_stop", f"pcb_stand_before {i} {near}", "wait 30",
                                                   "pcb_assert_transits reset", f"pcb_aim_track {i}", "+forward", "wait 150", "-forward"])
            attempt(f"{pair} jump into {i} #{r}", ["pcb_noclip_set 0", "pcb_stop", f"pcb_stand_before {i} {mid}", "wait 30",
                                                   "pcb_assert_transits reset", f"pcb_aim_track {i}", "+forward", "wait 12", "+jump", "wait 6", "-jump", "wait 140", "-forward"])
            # (from the air: the ground in front of a wall portal is only guaranteed for 3 blocks)
            attempt(f"{pair} fling into {i} #{r}", ["pcb_noclip_set 1", f"pcb_goto_aim {i} {far} {40 * (r * 2 - 1)}", "pcb_stop", "wait 30", "pcb_noclip_set 0",
                                                    "pcb_assert_transits reset", f"pcb_aim_track {i}", f"pcb_launch_to p{i} {400 if kind == 'chamber' else 520}", "wait 150"])
        else:  # floor portal in the region
            attempt(f"{pair} walk onto {i} #{r}", ["pcb_noclip_set 0", "pcb_stop", f"pcb_stand_before {i} 75 {90 * r}", "wait 30",
                                                   "pcb_assert_transits reset", f"pcb_aim_track {i}", "+forward", "wait 120", "-forward"])
            attempt(f"{pair} jump onto {i} #{r}", ["pcb_noclip_set 0", "pcb_stop", f"pcb_stand_before {i} 95 {90 * r + 45}", "wait 30",
                                                   "pcb_assert_transits reset", f"pcb_aim_track {i}", "+forward", "wait 6", "+jump", "wait 6", "-jump", "wait 120", "-forward"])
            attempt(f"{pair} drop into {i} #{r}", ["pcb_noclip_set 1", f"pcb_goto_aim {i} 460 0", "wait 20", "pcb_noclip_set 0",
                                                   "pcb_assert_transits reset", f"pcb_aim_track {i}", "wait 150"])

def prof(pair, i):
    w(f"pcb_view_from {i} 6", "wait 60", "pcb_composite_lag", "wait 180", f"pcb_log PROF {pair} still", "pcb_composite_lag",
      f"pcb_aim_track {i}", "+back", "wait 90", "-back", "+forward", "wait 90", "-forward", "pcb_aim_track off", f"pcb_log PROF {pair} walk", "pcb_composite_lag",
      "pcb_cam_turn 180 180", "wait 130", "pcb_cam_turn -180 180", "wait 130", f"pcb_log PROF {pair} turn", "pcb_composite_lag")

def pair(name, setup, kinds, transit_fn=None):
    w(f"pcb_log PAIR {name}", f"pcb_transit_set reset {name}", "pcb_assert_own_streams reset", "pcb_assert_stuck reset")
    w(*setup)
    w("pcb_assert_portals", "wait 30")
    for i in (0, 1):
        if kinds[i] != "chamber-skip":
            view_suite(name, i, kinds[i])
    w(f"pcb_transit_set assert m {name}", "pcb_assert_own_streams")
    prof(name, 1 if kinds[1] != "chamber" else 0)
    if transit_fn:
        transit_fn()
    else:
        for i in (0, 1):
            transits(name, i, kinds[i], 1 if SHORT else 2)
    w("pcb_assert_stuck 0", "pcb_assert_mc_alive 30", "pcb_assert_mc_alive reset")

def gun(colour, kind, orient, where=None, like=-1, radius=24):
    lines = []
    if where:
        lines += ["pcb_noclip_set 1", f"setpos {where[0]} {where[1]} {where[2]}", "pcb_stop", "wait 30", "waituntil near 1800", "wait 60"]
    b = "+attack" if colour == 0 else "+attack2"
    lines += ["waituntil terrain_idle 1200", f"pcb_find_surface {kind} {radius} {like}", "wait 20", b, "wait 6", "-" + b[1:], "wait 40",
              f"pcb_assert_gun_shot {colour} placed {orient}", f"pcb_assert_portal_face {colour}"]
    return lines

w("pcb_log PART2-3 pairs: preview stability, transits, frame times")
pair("groundcliff", gun(0, "ground", "floor", GROUND) + gun(1, "wall", "wall", GROUND, radius=64), ["floor", "wall"])
pair("cliffcliff", gun(0, "wall", "wall", GROUND, radius=64) + gun(1, "wall", "wall", like=0, radius=64), ["wall", "wall"])

def endless_fall():
    for i in (0, 1):
        attempt(f"groundground endless fall from {i}", ["pcb_noclip_set 1", f"pcb_goto_aim {i} 460 0", "wait 20", "pcb_noclip_set 0",
                                                         "pcb_assert_transits reset", "wait 420"], want=4)
    for i in (0, 1):
        transits("groundground", i, "floor", 1)
pair("groundground", gun(0, "ground", "floor", GROUND) + gun(1, "ground", "floor", like=0), ["floor", "floor"], endless_fall)

def facing_transits():
    for r in range(1 if SHORT else 2):
        for i, j in ((1, 0), (0, 1)):
            attempt(f"facing fling into {i} #{r}", ["pcb_noclip_set 1", f"pcb_corridor_aim {i}", "pcb_stop",
                                                     "wait 20", "pcb_noclip_set 0", "wait 2", "pcb_assert_transits reset", f"pcb_launch_to p{i} 400", "wait 90"])
# the facing pair (tunnel): two stone walls built in open air 12 blocks apart (pcb_build_corridor; removed at
# the end), both portals shot with the gun; no more pcb_portal placements in mid-air
pair("facing", ["pcb_noclip_set 1", f"setpos {GROUND[0]} {GROUND[1]} {GROUND[2]}", "pcb_stop", "wait 30", "waituntil near 1800", "waituntil terrain_idle 1200",
                "pcb_build_corridor -376 89 442 12", "wait 30", "waituntil corridor 1200", "waituntil terrain_idle 1200",
                "pcb_corridor_aim 0", "wait 20", "+attack", "wait 6", "-attack", "wait 40", "pcb_assert_gun_shot 0 placed wall",
                "pcb_corridor_aim 1", "wait 20", "+attack2", "wait 6", "-attack2", "wait 40", "pcb_assert_gun_shot 1 placed wall", "pcb_assert_portal_face"],
     ["wall", "wall"], facing_transits)
w("pcb_build_corridor remove", "wait 30")

chamber_setup = ["pcb_noclip_set 1", f"setpos {CHAMBER_EYE[0]} {CHAMBER_EYE[1]} {CHAMBER_EYE[2]}", "pcb_stop", "wait 30",
                 "pcb_aim 300 -512 -712", "wait 20", "+attack", "wait 6", "-attack", "wait 40", "pcb_assert_portal 0 300 -511 -712 64"] + gun(1, "ground", "floor", GROUND)
pair("mcchamber", chamber_setup, ["chamber", "floor"])

# ---- part 4: persistence -----------------------------------------------------------------------
w("pcb_log PART4 persistence")
w("pcb_log PAIR persist")
w(*gun(0, "ground", "floor", GROUND))
w(*gun(1, "wall", "wall", GROUND, radius=64))
w("pcb_assert_portals", "pcb_portal_mark")
case("S1", "30 s")
w("pcb_view_from 1 6", "wait 1800", "pcb_assert_portals_unchanged 30s")
case("S2", "night")
w("pcb_mc_cmd time set midnight", "wait 180", "pcb_assert_portals_unchanged night",
  "pcb_view_from 1 6", "wait 40", "pcb_frame_watch 6000 night mcworld", "wait 120", "pcb_frame_watch 0", "wait 5", "pcb_assert_watch", "screenshot pcb_S2_night",
  "pcb_view_from 0 6", "wait 40", "screenshot pcb_S2_night_ground", "pcb_mc_cmd time set day", "wait 120")
case("S3", "hidden player relocated 150 blocks out and back")
w("pcb_view_from 1 6", "wait 20", "pcb_fly_to -6200 -40 -13900 1500", "wait 330", "waituntil near 1800", "wait 60", "pcb_assert_portals_unchanged far150",
  "pcb_fly_to p1 240 1500", "wait 330", "waituntil near 1800", "wait 120", "pcb_assert_portals_unchanged back150")
case("S4", "chunks unloaded (~500 blocks out) and back")
w("pcb_fly_to 14500 14500 -13900 2500", "wait 600", "waituntil near 3600", "wait 600", "pcb_assert_portals_unchanged far500",
  "pcb_fly_to p1 240 2500", "wait 600", "waituntil near 3600", "wait 300", "pcb_assert_portals_unchanged back500",
  "pcb_view_from 1 6", "wait 60", "pcb_frame_watch 6000 back500 mcworld", "wait 120", "pcb_frame_watch 0", "wait 5", "pcb_assert_watch", "screenshot pcb_S4_back",
  "pcb_assert_stuck reset")
attempt("persist drop into the ground portal after the trip", ["pcb_noclip_set 1", "pcb_goto_aim 0 460 0", "wait 20", "pcb_noclip_set 0", "pcb_assert_transits reset", "wait 150"])
w("pcb_assert_stuck 0", "pcb_assert_portals_unchanged end")

# the Chell proxy (off in the suite: mob hits push Chell off her scripted drops) still works
case("X1", "Chell proxy on: a zombie at night hits her")
w("pcb_noclip_set 1", f"setpos {GROUND[0]} {GROUND[1]} {GROUND[2]}", "pcb_stop", "wait 30", "pcb_noclip_set 0", "wait 60",
  "pcb_chell_proxy 1 1", "wait 120", "pcb_mc_cmd time set midnight", "pcb_mc_cmd kill @e[type=!player,type=!portalcraft:skyrim_actor]", "wait 60",
  "pcb_assert_chell_hit reset", "pcb_mc_summon_near zombie 5 0", "wait 900", "pcb_chell_proxy", "pcb_assert_chell_hit 1",
  "pcb_mc_cmd kill @e[type=zombie]", "pcb_mc_cmd time set day", "pcb_chell_proxy 0", "wait 30")
w("pcb_log PROF all", "pcb_composite_lag", "pcb_assert_mc_alive 30", "pcb_assert_vmsize 3200", "pcb_run_summary", "quit")

with open(OUT, "w") as f:
    f.write("\n".join(L) + "\n")
print(f"{OUT}: {len(L)} lines, ~{sum(int(x.split()[1]) for x in L if x.startswith('wait ')) / 60:.0f} s of waits")
