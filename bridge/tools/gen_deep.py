#!/usr/bin/env python3
"""deep1 (bridge #12): Chell on Minecraft collision at every depth. The user: "collision of blocks breaks if I go
low enough, like in caves, past a height it breaks". A pocket is carved every 8 blocks from y 90 down to y -60 in one
column (stone floor at y-1, air y..y+3, 11 x 5 blocks); Chell is stepped down to each through the floating origin
(vertical shifts), dropped from 1 block with noclip off, must stand on its floor, then walks 1 s along it and must
still stand on it at walking speed. Then natural (never carved, never visited) caves ~330 blocks away at y -50..-30:
pcb_find_cave puts her on a floor found in the streamed collision; she must stand and walk there.
World hygiene: the pockets change region r.-1.0.mca; back it up (region/entities/poi) before and restore after
Minecraft has quit (cache/bridge/world_backup/carry12/)."""
import sys

X, Z = -372, 450
levels = list(range(90, -61, -8)) + [-60]
out = []
w = out.append
w("# generated by tools/gen_deep.py: " + __doc__.splitlines()[0])
for line in __doc__.splitlines()[1:]:
    w("# " + line if line else "#")
w("pcb_assert_soft 1\nsv_cheats 1\npcb_audio_test_mute 1\nwaituntil spawned 600\nwaituntil link 9000\nwaituntil haveexit 3600")
w("pc_pit_redirect 0\npcb_chell_proxy 0\npcb_mc_cmd time set noon\npcb_blockers watch 1")
w(f"pcb_noclip_set 1\npcb_light_goto_mc {X} 100 {Z} 90 0\npcb_stop\nwait 60")
for y in levels:
    w(f"pcb_mc_cmd fill {X-3} {y-1} {Z-2} {X+7} {y-1} {Z+2} stone")
    w(f"pcb_mc_cmd fill {X-2} {y} {Z-1} {X+6} {y+3} {Z+1} air")
w("wait 120")
for y in levels:
    w(f"pcb_log DEPTH y {y}")
    w("pcb_noclip_set 1")
    for _ in range(3):
        w(f"pcb_float_step_to {X} {y+1.5} {Z}\nwait 20")
    w("waituntil terrain_idle 1200")
    # radius 1: the pocket's own sections (Chell's hull at X+0.5, Z+0.5). Radius 3 reached z 447, section 27, whose
    # all-air sky sections Minecraft never sends (bridge #12's 4 "MISSING" were those, not a streaming gap)
    w(f"pcb_assert_sections_mc {X} {y} {Z} 1")
    w(f"pcb_light_goto_mc {X+0.5} {y+1} {Z+0.5} -90 0")  # MC yaw -90 = +X
    w("pcb_stop\nwait 20\npcb_noclip_set 0\nwait 120\npcb_where")
    w(f"pcb_assert_feet_mcy {y-0.05} {y+0.3}")
    w("pcb_blockers reset\npcb_blockers speedwin 1\n+forward\nwait 60\n-forward\npcb_blockers speedwin 0\nwait 30\npcb_where")
    w(f"pcb_assert_feet_mcy {y-0.05} {y+0.3}")
    w(f"pcb_assert_blockers depth{y} 150")
w("pcb_log NATURAL caves ~330 blocks away, y -50..-30 (never carved, never visited this run)")
w("pcb_noclip_set 1")
for _ in range(8):
    w("pcb_float_step_to -100 -38 200\nwait 30")
w("pcb_where\nwaituntil terrain_idle 1800")
for i, (cx, cz) in enumerate([(-100, 200), (-60, 230), (-140, 170)]):
    w(f"pcb_log NATURAL cave {i}")
    w("pcb_noclip_set 1")
    w(f"pcb_float_step_to {cx} -38 {cz}\nwait 30\nwaituntil terrain_idle 1200")
    w(f"pcb_find_cave {cx} {cz} -50 -30 32")
    w("wait 10\npcb_stop\nwait 20\npcb_noclip_set 0\nwait 150\npcb_where\npcb_assert_cave_feet 0.5")
    w("+forward\nwait 50\n-forward\nwait 60\npcb_where\npcb_assert_cave_feet 4")
w("pcb_assert_mc_alive 30\npcb_run_summary\nquit")
open(sys.argv[1] if len(sys.argv) > 1 else "tools/cfg/deep1.txt", "w").write("\n".join(out) + "\n")

# deep2: moving across vertical floating-origin shifts with block collision on (float4 crossed them in noclip only).
# A: a 3 x 3 shaft from y 85 down to a stone floor at y -59 in one column: Chell falls ~144 blocks with collision on
# and must land on the floor and stand (every vertical shift on the way happens mid-fall). B: a staircase tunnel
# (1 block down every 2 blocks, y 60 -> 21, then a flat landing at y 21) walked with +forward across the shifts;
# she must reach the landing and stand on it. Each shift is logged; pcb_float_trace shows the eye after each.
SX, SZ = -360, 466
TX, TZ = -350, 474
o = []
w = o.append
w("# generated by tools/gen_deep.py (deep2): falling and walking across vertical floating-origin shifts with block collision on")
w("# World hygiene: as deep1 (region r.-1.0.mca, backup cache/bridge/world_backup/carry12/).")
w("pcb_assert_soft 1\nsv_cheats 1\npcb_audio_test_mute 1\nwaituntil spawned 600\nwaituntil link 9000\nwaituntil haveexit 3600")
w("pc_pit_redirect 0\npcb_chell_proxy 0\npcb_mc_cmd time set noon\npcb_blockers watch 1")
w(f"pcb_noclip_set 1\npcb_light_goto_mc {SX} 100 {SZ} 90 0\npcb_stop\nwait 60")
w(f"pcb_mc_cmd fill {SX-1} -58 {SZ-1} {SX+1} 85 {SZ+1} air")
w(f"pcb_mc_cmd fill {SX-2} -59 {SZ-2} {SX+2} -59 {SZ+2} stone")
for i in range(40):
    y = 60 - i
    x = TX + 2 * i
    w(f"pcb_mc_cmd fill {x} {y-1} {TZ-1} {x+1} {y-1} {TZ+1} stone")
    w(f"pcb_mc_cmd fill {x} {y} {TZ-1} {x+1} {y+3} {TZ+1} air")
LX = TX + 80
w(f"pcb_mc_cmd fill {LX} 20 {TZ-1} {LX+5} 20 {TZ+1} stone")
w(f"pcb_mc_cmd fill {LX} 21 {TZ-1} {LX+5} 24 {TZ+1} air")
w("wait 180")
w("pcb_log SHAFT fall from y 85 to the floor at y -59 (collision on)")
w(f"pcb_light_goto_mc {SX+0.5} 86 {SZ+0.5} 0 0\npcb_stop\nwait 20\nwaituntil terrain_idle 1200")
w("pcb_float_trace 6\npcb_blockers reset\npcb_noclip_set 0\npcb_track 2400 20")
w("waituntil mcybelow-50 1800\nwait 240\npcb_where")
w("pcb_assert_feet_mcy -58.05 -57.7")
w("wait 120\npcb_where\npcb_assert_feet_mcy -58.05 -57.7\npcb_assert_stuck")  # (still on the floor top, -58: bridge #13; it read -59)
w("pcb_log STAIRS walk down y 60 -> 21 across the shifts (collision on; vertical margin 120 blocks so the walk crosses several)")
w("pc_mc_float 1 200 120")
w("pcb_noclip_set 1")
for _ in range(4):
    w(f"pcb_float_step_to {TX+0.5} 62 {TZ+0.5}\nwait 20")
w("waituntil terrain_idle 1200")
w(f"pcb_light_goto_mc {TX+0.5} 60 {TZ+0.5} -90 0\npcb_stop\nwait 20\npcb_noclip_set 0\nwait 90")
w("pcb_assert_feet_mcy 59.95 60.3")
w("pcb_blockers reset\npcb_assert_stuck reset\npcb_float_trace 6\npcb_track 2400 20\n+forward")
w(f"waituntil mcxabove{LX+1} 2400\n-forward\nwait 120\npcb_where")
w("pcb_assert_feet_mcy 20.95 21.3\npcb_assert_stuck\npcb_blockers report stairs")
w("pcb_assert_mc_alive 30\npcb_run_summary\nquit")
open("tools/cfg/deep2.txt", "w").write("\n".join(o) + "\n")
