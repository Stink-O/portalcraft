#!/usr/bin/env python3
"""Generate tools/cfg/mcportals1.txt: the gate for the Minecraft-side portal renderer (DESIGN-mcportals.md,
bridge agent #7). Every portal is placed by Chell's gun on a real block face (pcb_assert_portal_face).

  tools/gen_mcportals.py [--before] [--short] [out]

--before: the same run with `pcb_mc_portals 0` (today's multi-stream path), for the before/after comparison.
Pairs:
  cliffcliff  two portals on the natural cliff walls below the clip area (the second "like" the first)
  groundcliff a ground portal and a cliff-wall portal; a weighted cube in front of the wall portal, seen
              through the ground portal
  corridor    two stone walls built in open air facing each other 12 blocks apart (removed afterwards):
              the facing tunnel (recursion), Chell's own body seen through both portals
Per pair and portal: still views at 3 and 8 blocks with every frame watched (white, stale, foreign),
still-preview stability (clouds), image age, twitch standing still; close-ups at 1 and 3 blocks straight on
and at 45 deg (both colours); frame-time windows (still / walk / turn).
"""
import sys

BEFORE = "--before" in sys.argv
SHORT = "--short" in sys.argv
args = [a for a in sys.argv[1:] if not a.startswith("--")]
OUT = args[0] if args else ("tools/cfg/mcportals1_before.txt" if BEFORE else "tools/cfg/mcportals1.txt")
GROUND = (-1911, -194, -15100)
L = []
w = lambda *x: L.extend(x)

def go(p, settle=60):
    w("pcb_noclip_set 1", f"setpos {p[0]} {p[1]} {p[2]}", "pcb_stop", "wait 30", "waituntil near 1800", f"wait {settle}", "waituntil terrain_idle 1200")

def gun(colour, kind, radius=64, like=-1):
    b = "+attack" if colour == 0 else "+attack2"
    w("waituntil terrain_idle 1200", f"pcb_find_surface {kind} {radius} {like}", "wait 20", b, "wait 6", "-" + b[1:], "wait 40")

def placed(orient0, orient1):
    w("pcb_assert_portals", "wait 30", "waituntil terrain_idle 1200", "pcb_assert_portal_face")

def views(pair, dists=(3, 8)):
    for i in (0, 1):
        for d in dists:
            lab = f"{pair}_p{i}_d{d}"
            w(f"pcb_log VIEW {lab}", f"pcb_view_from {i} {d}", "pcb_stop", "wait 60",
              f"pcb_frame_watch 2000 {lab} mcworld", "pcb_assert_still_stable reset", "pcb_assert_image_age reset", "pcb_twitch reset", "pcb_assert_own_streams reset",
              "wait 240", "pcb_assert_still_stable 1.0 6", "pcb_assert_image_age 3 6", f"pcb_twitch report {lab}_still 0.5 2", "pcb_assert_own_streams",
              "pcb_frame_watch 0", "wait 5", "pcb_assert_watch", f"screenshot pcb_{lab}")

def closeups(pair):
    w("pcb_noclip_set 1")  # (a 1-block pose puts the feet below the opening's floor: without noclip Portal 2 pushes the player out, a moving camera)
    for i in (0, 1):
        for _ in range(6):
            w(f"pcb_view_portal {i} 40 0 1", "pcb_stop", "wait 8")
        w(f"screenshot pcb_{pair}_p{i}_close_d1")
        for d, lab in ((120, "d3a45"), (40, "d1a45")):
            for _ in range(6):
                w(f"pcb_view_portal {i} {d} 45 1", "pcb_stop", "wait 8")
            w(f"screenshot pcb_{pair}_p{i}_close_{lab}")

def prof(pair, i=0):
    w(f"pcb_view_from {i} 6", "pcb_stop", "wait 60", "pcb_composite_lag", "wait 180", f"pcb_log PROF {pair} still", "pcb_composite_lag",
      f"pcb_aim_track {i}", "+back", "wait 90", "-back", "+forward", "wait 90", "-forward", "pcb_aim_track off", "pcb_stop", f"pcb_log PROF {pair} walk", "pcb_composite_lag",
      "pcb_cam_turn 180 180", "wait 130", "pcb_cam_turn -180 180", "wait 130", f"pcb_log PROF {pair} turn", "pcb_composite_lag", "pcb_stop")

w(f"# mcportals1{'_before' if BEFORE else ''}: the Minecraft-side portal renderer's gate (generated by tools/gen_mcportals.py)",
  "pcb_assert_soft 1", "sv_cheats 1", "waituntil spawned 600", "waituntil link 9000", "waituntil haveexit 3600",
  "pc_pit_redirect 0", "pcb_noclip_set 1", "sv_noclipspeed 1", "cl_yawspeed 180", "pcb_chell_proxy 0", "pcb_assert_mc_alive reset",
  "pcb_mc_cmd time set noon", "pcb_mc_cmd weather clear", f"pcb_mc_portals {0 if BEFORE else 1}", "pcb_composite_lag")

# ---- cliff <-> cliff ---------------------------------------------------------------------------
w("pcb_log PAIR cliffcliff")
go(GROUND, 120)
gun(0, "wall")
gun(1, "wall", like=0)
placed("wall", "wall")
views("cliffcliff")
closeups("cliffcliff")
prof("cliffcliff")

# ---- cliff <-> cliff side by side (cloud1a's pair: the second shot at the first one's spot, bumped beside
# it by Portal 2's fitting), both views sharing the sky: the cloud twitch case -----------------------------
w("pcb_log PAIR cliffadjacent")
go(GROUND)
gun(0, "wall")
w("wait 20", "+attack2", "wait 6", "-attack2", "wait 40")  # (same pose and aim: Portal 2 bumps the second portal beside the first)
placed("wall", "wall")
views("cliffadjacent", (3,) if SHORT else (3, 8))
w("pcb_view_from 0 3", "pcb_stop", "wait 60", "screenshot pcb_cliffadjacent_close_d3")

# ---- ground <-> cliff, a cube seen through the ground portal --------------------------------------
w("pcb_log PAIR groundcliff")
go(GROUND)
gun(0, "ground", 24)
gun(1, "wall")
placed("floor", "wall")
views("groundcliff", (3,) if SHORT else (3, 8))
w("pcb_spawn_cube_before 1 90 pcb_gatecube", "wait 120", "pcb_assert_prop_rest pcb_gatecube")
w("pcb_log CASE cube through the ground portal", "pcb_view_through 0 pcb_gatecube 3", "pcb_stop", "wait 60", "pcb_assert_seen_through 0 pcb_gatecube", "wait 10",
  "screenshot pcb_groundcliff_cube_through_p0")
closeups("groundcliff")
prof("groundcliff", 1)
w("ent_fire pcb_gatecube kill", "wait 10")

# ---- the facing corridor (built in open air) --------------------------------------------------------
w("pcb_log PAIR corridor")
go(GROUND)
w("pcb_build_corridor -376 89 442 12", "wait 30", "waituntil corridor 1200", "waituntil terrain_idle 1200",
  "pcb_corridor_aim 0", "wait 20", "+attack", "wait 6", "-attack", "wait 40",
  "pcb_corridor_aim 1", "wait 20", "+attack2", "wait 6", "-attack2", "wait 40")
placed("wall", "wall")
views("corridor", (3,) if SHORT else (3, 8))
for i in (0, 1):
    w(f"pcb_log CASE Chell seen through portal {i}", f"pcb_view_from {i} 3", "pcb_stop", "wait 60", f"pcb_assert_seen_through {i} chell", "wait 10",
      f"screenshot pcb_corridor_chell_through_p{i}")
closeups("corridor")
prof("corridor")
# the open animation, frame by frame: Portal 2's visible opening (its portal views filled magenta) against the
# opening in the Minecraft image on screen that frame; the orange portal re-placed across the east wall
w("pcb_log CASE open animation", "pcb_mc_portals_shape 27 47 0 3", "r_drawviewmodel 0", "pcb_measure_open reset")
for k, dz in enumerate((-1.6, 1.6, -1.6)):
    w(f"pcb_corridor_aim 1 {dz}", "pcb_stop", "wait 30", "+attack2", "wait 2", "-attack2", "pcb_measure_open 1 120", "wait 220")
w("pcb_measure_open assert 0")
w("pcb_log CASE open animation, the same spot again (known: up to 2 frames of the previous opening)", "pcb_measure_open reset",
  "pcb_corridor_aim 1 -1.6", "pcb_stop", "wait 30", "+attack2", "wait 2", "-attack2", "pcb_measure_open 1 120", "wait 220", "pcb_measure_open assert 2",
  "pcb_mc_portals_shape 27 47 0 0", "r_drawviewmodel 1")
w("pcb_build_corridor remove", "wait 30")

w("pcb_log PROF all", "pcb_composite_lag", "pcb_mc_portals", "pcb_assert_mc_alive 30", "pcb_run_summary", "quit")
with open(OUT, "w") as f:
    f.write("\n".join(L) + "\n")
print(f"{OUT}: {len(L)} lines, ~{sum(int(x.split()[1]) for x in L if x.startswith('wait ')) / 60:.0f} s of waits")
